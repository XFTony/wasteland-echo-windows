"""Mechanical export/registration of an ImageGen prop; no creative repainting."""
from pathlib import Path
import csv
import hashlib
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'art/world/echo-market-v1/source/trade-post.png'
RUNTIME = ROOT / 'web/assets/world/echo-market-v1/trade-post.webp'

image = Image.open(SOURCE).convert('RGBA')
assert image.getchannel('A').getextrema()[0] == 0, 'Expected genuine transparent source'
bounds = image.getchannel('A').point(lambda alpha: 255 if alpha > 16 else 0).getbbox()
cropped = image.crop(bounds)
exported = cropped.resize((380, round(380 * cropped.height / cropped.width)), Image.Resampling.NEAREST)
RUNTIME.parent.mkdir(parents=True, exist_ok=True)
exported.save(RUNTIME, lossless=True, exact=True, method=6)
assert Image.open(RUNTIME).convert('RGBA').tobytes() == exported.tobytes(), 'Lossless export changed pixels'
asset_id = 'world.prop.echo.market.v1'
manifest_path = ROOT / 'art/manifest.json'
manifest = json.loads(manifest_path.read_text('utf-8'))
ids = {asset_id, 'world.prop.echo.salvage-kit.v1'}
manifest['assets'] = [entry for entry in manifest['assets'] if entry['id'] not in ids]
record = {'id': asset_id, 'version': 'echo-market-v1', 'status': 'active',
          'runtimePath': RUNTIME.relative_to(ROOT).as_posix(),
          'archivePath': SOURCE.relative_to(ROOT).as_posix(),
          'sourcePaths': ['art/world/echo-market-v1/source/generation-record.json', 'art/world/echo-market-v1/README.md'],
          'width': exported.width, 'height': exported.height, 'bytes': RUNTIME.stat().st_size,
          'sha256': hashlib.sha256(RUNTIME.read_bytes()).hexdigest().upper(),
          'generator': 'OpenAI built-in ImageGen', 'sourceAlphaBounds': list(bounds),
          'notes': 'Transparent source trimmed to alpha bounds and nearest-neighbor exported. Solid footprint and counter interaction remain world data; text and icons are code-drawn.'}
kit_source = ROOT / 'art/world/echo-market-v1/source/salvage-kit.png'
kit_image = Image.open(kit_source).convert('RGBA')
assert kit_image.getchannel('A').getextrema()[0] == 0
regions = json.loads((ROOT / 'art/world/echo-market-v1/source/salvage-kit-generation.json').read_text('utf-8'))['sourceRegions']
atlas = Image.new('RGBA', (512, 384), (0, 0, 0, 0))
rects = {}
for index, (name, region) in enumerate(regions.items()):
    cell = kit_image.crop(region)
    bbox = cell.getchannel('A').point(lambda alpha: 255 if alpha > 16 else 0).getbbox()
    assert bbox and bbox[0] > 1 and bbox[1] > 1 and bbox[2] < cell.width - 1 and bbox[3] < cell.height - 1, 'Clipped sprite: ' + name
    sprite = cell.crop(bbox)
    scale = min(240 / sprite.width, 176 / sprite.height)
    sprite = sprite.resize((round(sprite.width * scale), round(sprite.height * scale)), Image.Resampling.NEAREST)
    px = index % 2 * 256 + (256 - sprite.width) // 2
    py = index // 2 * 192 + (192 - sprite.height) // 2
    atlas.paste(sprite, (px, py))
    rects[name] = [px, py, sprite.width, sprite.height]
kit_runtime = RUNTIME.with_name('salvage-kit.webp')
atlas.save(kit_runtime, lossless=True, exact=True, method=6)
assert Image.open(kit_runtime).convert('RGBA').tobytes() == atlas.tobytes()
descriptor = ROOT / 'src/content/echo-props.js'
descriptor.write_text('"use strict";\n// Generated by stage-echo-market-assets.py. World collision stays in map data.\nmodule.exports = ' + json.dumps({'ECHO_PROP_RECTS': rects}, indent=2) + ';\n', 'utf-8')
kit = {'id': 'world.prop.echo.salvage-kit.v1', 'version': 'echo-market-v1', 'status': 'active',
       'runtimePath': kit_runtime.relative_to(ROOT).as_posix(), 'archivePath': kit_source.relative_to(ROOT).as_posix(),
       'sourcePaths': ['art/world/echo-market-v1/source/salvage-kit-generation.json', 'art/world/echo-market-v1/README.md', 'src/content/echo-props.js'],
       'width': atlas.width, 'height': atlas.height, 'bytes': kit_runtime.stat().st_size,
       'sha256': hashlib.sha256(kit_runtime.read_bytes()).hexdigest().upper(), 'generator': 'OpenAI built-in ImageGen',
       'spriteRects': rects, 'notes': 'Four alpha-cropped prop sprites packed with gutters; lossless nearest-neighbor export. No collision embedded in the image.'}
records = [record, kit]
manifest['assets'].extend(records)
manifest['updatedAt'] = '2026-10-28'
manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', 'utf-8')
ledger_path = ROOT / 'docs/assets-ledger.csv'
with ledger_path.open(encoding='utf-8-sig', newline='') as handle:
    reader = csv.DictReader(handle)
    fields, rows = reader.fieldnames, [row for row in reader if row['asset_id'] not in ids]
for item in records:
    rows.append(dict(zip(fields, [item['id'], 'pixel-world-landmark', item['runtimePath'], '',
        'Wasteland Echo / OpenAI ImageGen', 'Generated project asset; service terms review',
        '2026-10-28', 'true', '', 'pending', 'review-before-commercial-release'])))
with ledger_path.open('w', encoding='utf-8', newline='') as handle:
    writer = csv.DictWriter(handle, fieldnames=fields); writer.writeheader(); writer.writerows(rows)
print(json.dumps({'assets': records, 'runtimeBytes': sum(item['bytes'] for item in records)}, ensure_ascii=False))
