"""Stage lossless live textures and generate runtime descriptors from art sources."""
from pathlib import Path
import csv
import hashlib
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / 'art/characters/ranger/modular-grips-v3'
OUT = ROOT / 'web/assets/actors/compact-v1'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest().upper()


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    data = json.loads((ART / 'metadata.json').read_text('utf-8'))
    enemies = json.loads((ROOT / 'art/enemies/compact-v1/metadata.json').read_text('utf-8'))
    character = data['characters'][data['defaultCharacter']]
    ids, catalog, entries = {}, {}, []

    def register(symbol, asset_id, runtime, png, sources, group):
        runtime, png = Path(runtime), Path(png)
        ids[symbol] = asset_id
        catalog[asset_id] = {'id': asset_id, 'src': './' + runtime.relative_to(ROOT / 'web').as_posix(),
                             'group': group, 'version': 'compact-v1', 'optional': True,
                             'active': True, 'eager': False, 'nineSlice': None,
                             'notes': 'Compact native pixel art; lossless runtime export; loaded on demand.'}
        image = Image.open(runtime)
        entries.append({'id': asset_id, 'version': 'compact-v1', 'status': 'active',
                        'runtimePath': runtime.relative_to(ROOT).as_posix(),
                        'archivePath': png.relative_to(ROOT).as_posix(),
                        'sourcePaths': [Path(p).relative_to(ROOT).as_posix() for p in sources if Path(p).exists()],
                        'width': image.width, 'height': image.height, 'bytes': runtime.stat().st_size,
                        'sha256': sha(runtime), 'generator': 'OpenAI ImageGen + project native pixel import',
                        'notes': 'Source ownership, editable native file and runtime texture kept separately.'})

    def stage(png, name):
        image = Image.open(png).convert('RGBA')
        target = OUT / (name + '.webp')
        image.save(target, lossless=True, exact=True, method=6)
        if Image.open(target).convert('RGBA').tobytes() != image.tobytes():
            raise ValueError('Non-exact texture export: ' + name)
        return target

    body_png = (ART / character['bodyAtlas']).resolve()
    body_runtime = stage(body_png, 'ranger-body')
    register('COMPACT_RANGER', 'actor.compact.ranger.v1', body_runtime, body_png,
             [body_png.with_name('body-frames.aseprite')], 'compact-actors')
    used = {w['visual']['asset'] for w in data['weapons']}
    selected_hands = data['handSets'][character['defaultHands']]
    selected_cuffs = data['cuffSets'][character['defaultCuffs']]
    used.update(['hands.' + character['defaultHands'], 'cuffs.' + character['defaultCuffs']])
    part_ids = {}
    for key in sorted(used):
        definition = data['assets'][key]
        png = (ART / definition['path']).resolve()
        name = key.replace('.', '-').replace('_', '-')
        runtime = stage(png, name)
        asset_id = 'compact.part.' + key + '.v1'
        part_ids[key] = asset_id
        symbol = 'COMPACT_' + key.replace('.', '_').replace('-', '_').upper()
        native = png.with_name('weapon-base.aseprite' if key.startswith('weapon.') else 'poses.aseprite')
        register(symbol, asset_id, runtime, png, [native], 'compact-parts')
    for key, enemy in enemies['enemies'].items():
        register('COMPACT_' + key.upper(), enemy['assetId'], ROOT / enemy['runtime'],
                 ROOT / enemy['atlas'], [ROOT / enemy['source'], ROOT / enemy['sourceDrawing'],
                 ROOT / 'art/enemies/compact-v1/source/generation-record.json'], 'compact-enemies')

    material_data = {key: data[key] for key in ['schemaVersion', 'weapons', 'characters', 'defaultCharacter',
                                              'defaultWeapon', 'defaultHands', 'defaultCuffs']}
    material_data['handSets'] = {selected_hands['id']: selected_hands}
    material_data['cuffSets'] = {selected_cuffs['id']: selected_cuffs}
    runtime = {'HERO': {'heroId': 'ranger', 'skinId': 'wanderer', 'assetId': ids['COMPACT_RANGER'],
                        'pixelScale': 1.5, 'stride': 68, 'body': character['body']},
               'MATERIALS': material_data, 'PART_ASSETS': part_ids,
               'ENEMY_SPRITES': {key: {k: v for k, v in enemy.items() if k in
                                      ['assetId', 'canvas', 'columns', 'root', 'idleFrame', 'walkFrames', 'stride', 'pixelScale', 'referenceHeight']}
                                 for key, enemy in enemies['enemies'].items()}}
    (ROOT / 'src/content/compact-actors.js').write_text(
        '"use strict";\n// Generated by scripts/animation/stage-compact-live-assets.py from editable art descriptors.\nmodule.exports = ' +
        json.dumps(runtime, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    (ROOT / 'src/render/art/compact-asset-catalog.js').write_text(
        '"use strict";\n// Generated compact runtime asset definitions.\nmodule.exports = ' +
        json.dumps({'COMPACT_IDS': ids, 'COMPACT_ASSETS': catalog}, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    path = ROOT / 'art/manifest.json'
    manifest = json.loads(path.read_text('utf-8'))
    entry_ids = {entry['id'] for entry in entries}
    # Keep existing illustrated originals available for portraits/history; live
    # enemy rendering no longer requests them, and they do not enter staging.
    retired = {'actor.' + key.replace('_', '-') + '.v1' for key in enemies['enemies']}
    for item in manifest['assets']:
        if item['id'] in retired:
            item['status'] = 'inactive'
    manifest['assets'] = [item for item in manifest['assets'] if item['id'] not in entry_ids] + entries
    manifest['updatedAt'] = '2026-10-28'
    path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    ledger = ROOT / 'docs/assets-ledger.csv'
    with ledger.open(encoding='utf-8-sig', newline='') as handle:
        reader = csv.DictReader(handle)
        fields, rows = reader.fieldnames, list(reader)
    rows = [row for row in rows if row['asset_id'] not in entry_ids]
    for entry in entries:
        rows.append(dict(zip(fields, [entry['id'], 'pixel-animation', entry['runtimePath'], '',
                    'Wasteland Echo project / OpenAI ImageGen', 'Generated project asset; service terms review',
                    '2026-10-28', 'true', '', 'pending', 'review-before-commercial-release'])))
    with ledger.open('w', encoding='utf-8', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    print(json.dumps({'textures': len(entries), 'runtimeBytes': sum(e['bytes'] for e in entries),
                      'partsLoadedOnDemand': len(used)}))


if __name__ == '__main__':
    main()
