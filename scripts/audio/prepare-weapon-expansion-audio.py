"""Project original effects mixed with the already licensed local source recordings."""
from pathlib import Path
import json,hashlib,wave,math
import numpy as np
from scipy.io import wavfile
from scipy.signal import butter,sosfilt,resample_poly
ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'web/assets/audio/arsenal-v2'
SOURCE=ROOT/'art/audio/survival-v1/source'
ART=ROOT/'art/audio/arsenal-v2'
OUT.mkdir(parents=True,exist_ok=True);ART.mkdir(parents=True,exist_ok=True)
RATE=22050
rng=np.random.default_rng(102905)
def filtered(data,low,high):return sosfilt(butter(2,[low,high],btype='bandpass',fs=RATE,output='sos'),data)
def recorded(name,seconds):
 rate,data=wavfile.read(SOURCE/name)
 if data.ndim>1:data=data.mean(axis=1)
 data=data.astype(float)/32768
 if rate!=RATE:data=resample_poly(data,RATE//math.gcd(rate,RATE),rate//math.gcd(rate,RATE))
 threshold=max(abs(data))*.04;start=max(0,int(np.flatnonzero(abs(data)>threshold)[0])-32)
 out=np.zeros(round(seconds*RATE));part=data[start:start+len(out)];out[:len(part)]=part
 return out
def noise(t,low,high,decay):return filtered(rng.normal(size=len(t)),low,high)*np.exp(-t*decay)
def time(seconds):return np.arange(round(seconds*RATE))/RATE
assets=[]
def export(id,data,peak,role,source):
 data=np.asarray(data,float);data-=data.mean();fade=min(len(data)//3,round(.025*RATE));data[:32]*=np.linspace(0,1,32);data[-fade:]*=np.linspace(1,0,fade)
 data*=peak/max(.001,max(abs(data)));file=OUT/(id+'.wav')
 with wave.open(str(file),'wb')as w:w.setnchannels(1);w.setsampwidth(2);w.setframerate(RATE);w.writeframes((data*32767).astype('<i2').tobytes())
 assets.append(dict(id=id,src='./assets/audio/arsenal-v2/'+file.name,role=role,seconds=len(data)/RATE,bytes=file.stat().st_size,sha256=hashlib.sha256(file.read_bytes()).hexdigest().upper(),source=source))
t=time(.24);laser=noise(t,1300,6500,25)*.25+np.sin(2*np.pi*(460*t+25*(1-np.exp(-t*30))))*np.exp(-t*28)*.11
export('prism_laser',laser,.62,'shot','Original filtered discharge and short resonant snap')
t=time(.30);launcher=filtered(recorded('recording-20g.wav',.30),65,2100)*.8+noise(t,100,1300,18)*.10
export('slag_launcher',launcher,.77,'shot','SnakeF8 isolated shotgun, low-pass edit with original pressure layer')
t=time(.24);disc=noise(t,650,5500,19)*.18
for f,a in [(720,.09),(1130,.04),(1840,.025)]:disc+=np.sin(2*np.pi*f*t)*np.exp(-t*22)*a
export('saw_disc',disc,.57,'shot','Original filtered motor snap and metallic partials')
t=time(.22);swish=noise(t,250,4800,9)*np.sin(np.pi*np.minimum(1,t/.22))**1.5
export('echo_blade',swish,.47,'melee','Original noise-based air sweep, no gun recording')
t=time(.30);heavy=noise(t,120,2200,7)*np.sin(np.pi*np.minimum(1,t/.30))*.5
export('shock_hammer',heavy,.48,'melee','Original low air sweep')
t=time(.52);boom=filtered(recorded('recording-20g.wav',.52),45,1700)*.6+noise(t,60,2400,10)*.18+np.sin(2*np.pi*52*t)*np.exp(-t*14)*.07
export('explosion',boom,.82,'impact','SnakeF8 isolated shotgun edited; original noise and low impact')
t=time(.38);impact=filtered(recorded('recording-hammer.wav',.38),80,4200)*.28+noise(t,100,1800,16)*.25+np.sin(2*np.pi*67*t)*np.exp(-t*22)*.11
export('hammer_impact',impact,.81,'impact','SnakeF8 mechanical hammer recording; original thump and debris')
t=time(.14);metal=noise(t,1100,7000,36)*.23
for f,a in [(1010,.04),(1690,.035),(2300,.025)]:metal+=np.sin(2*np.pi*f*t)*np.exp(-t*38)*a
export('melee_hit',metal,.43,'impact','Original short metal transient')
t=time(.10);ricochet=noise(t,1600,8000,48)*.12+np.sin(2*np.pi*1380*t)*np.exp(-t*55)*.035
export('ricochet',ricochet,.36,'impact','Original short ricochet transient')
(ROOT/'src/content/expansion-audio-assets.js').write_text('"use strict";\n// Generated by scripts/audio/prepare-weapon-expansion-audio.py\nmodule.exports={EXPANSION_AUDIO_ASSETS:'+json.dumps(assets,ensure_ascii=False,indent=2)+'};\n',encoding='utf-8')
provenance=dict(date='2026-10-29',description='Original project effects; selected sounds derive from the existing SnakeF8 CC0 source recordings. See ../survival-v1/source-permission.md. No competitor audio copied.',runtime=assets,sourceFiles=[dict(path='../survival-v1/source/'+name,sha256=hashlib.sha256((SOURCE/name).read_bytes()).hexdigest().upper())for name in ['recording-20g.wav','recording-hammer.wav']])
(ART/'source-provenance.json').write_text(json.dumps(provenance,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps(dict(files=len(assets),bytes=sum(a['bytes']for a in assets))))
